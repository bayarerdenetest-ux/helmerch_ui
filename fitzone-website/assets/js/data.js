function fzLoad(name) {
  try {
    const v = localStorage.getItem("fz_admin_" + name);
    if (v) return fzMigrate(name, JSON.parse(v));
  } catch (e) { /* localStorage ашиглах боломжгүй */ }
  return JSON.parse(JSON.stringify(FZ_SEED[name] || []));
}
/* Өмнөх хувилбарт хадгалсан өгөгдөлд шинэ талбаруудыг нөхөж өгнө */
function fzMigrate(name, rows) {
  const seed = FZ_SEED[name] || [];
  const byId = id => seed.find(x => x.id === id) || {};
  if (name === "trainers") return rows.map(r => r.types ? r : {
    ...byId(r.id), ...r,
    short: r.short || byId(r.id).short || String(r.name || "").split(" ")[0],
    role: r.role || byId(r.id).role || r.specialty || "Дасгалжуулагч",
    types: byId(r.id).types || []
  });
  if (name === "classes") return rows.map(r => r.room !== undefined ? r : { ...r, room: byId(r.id).room || "" });
  return rows;
}
